// === Live view counter (localStorage-backed, per-article; +1 on each article view) ===
window.NITRO_VIEWS = {
  _key: function (id) { return "nitro_views_" + id; },
  delta: function (id) {
    try { return parseInt(localStorage.getItem(this._key(id)) || "0", 10) || 0; }
    catch (e) { return 0; }
  },
  bump: function (id) {
    try { var n = this.delta(id) + 1; localStorage.setItem(this._key(id), String(n)); return n; }
    catch (e) { return 0; }
  },
  apply: function () {
    var cols = window.NITRO_COLUMNS || [];
    for (var i = 0; i < cols.length; i++) {
      var c = cols[i];
      if (c._baseViews === undefined) {
        c._baseViews = parseInt(String(c.views || "0").replace(/[^0-9]/g, ""), 10) || 0;
      }
      c.views = (c._baseViews + this.delta(c.id)).toLocaleString("en-US");
    }
  }
};
window.NITRO_VIEWS.apply();
